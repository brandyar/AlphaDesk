function createField({
  collection,
  field,
  type = 'string',
  dataType = 'character varying',
  isPrimaryKey = false,
  isNullable = true,
  defaultValue = null,
  special = null,
  interfaceType = 'input',
  options = null,
  sort = 1,
  width = 'full',
  required = false,
  maxLength = 255,
  numericPrecision = null,
  numericScale = null,
  foreignKeyTable = null,
  foreignKeyColumn = null,
}) {
  return {
    collection,
    field,
    type,
    schema: {
      name: field,
      table: collection,
      data_type: dataType,
      default_value: defaultValue,
      generation_expression: null,
      max_length: maxLength,
      numeric_precision: numericPrecision,
      numeric_scale: numericScale,
      is_generated: false,
      is_nullable: isNullable,
      is_unique: isPrimaryKey,
      is_indexed: isPrimaryKey || !!foreignKeyTable,
      is_primary_key: isPrimaryKey,
      has_auto_increment: false,
      foreign_key_schema: foreignKeyTable ? 'public' : null,
      foreign_key_table: foreignKeyTable,
      foreign_key_column: foreignKeyColumn,
      comment: null,
    },
    meta: {
      collection,
      field,
      special,
      interface: interfaceType,
      options,
      display: null,
      display_options: null,
      readonly: isPrimaryKey && special?.includes('date-created'),
      hidden: isPrimaryKey,
      sort,
      width,
      translations: null,
      note: null,
      conditions: null,
      required,
      group: null,
      validation: null,
      validation_message: null,
      searchable: true,
    },
  };
}

function createCollection(collection, note, sort = 1) {
  return {
    collection,
    meta: {
      collection,
      icon: null,
      note,
      display_template: null,
      hidden: false,
      singleton: false,
      translations: null,
      archive_field: null,
      archive_app_filter: true,
      archive_value: null,
      unarchive_value: null,
      sort_field: null,
      accountability: 'all',
      color: null,
      item_duplication_fields: null,
      sort,
      group: null,
      collapse: 'open',
      preview_url: null,
      versioning: false,
    },
    schema: {},
  };
}

function createRelation(manyCollection, manyField, oneCollection, oneField = null) {
  return {
    collection: manyCollection,
    field: manyField,
    related_collection: oneCollection,
    schema: {
      constraint_name: `${manyCollection}_${manyField}_foreign`,
      table: manyCollection,
      column: manyField,
      foreign_key_schema: 'public',
      foreign_key_table: oneCollection,
      foreign_key_column: 'id',
      on_update: 'NO ACTION',
      on_delete: 'SET NULL',
    },
    meta: {
      many_collection: manyCollection,
      many_field: manyField,
      one_collection: oneCollection,
      one_field: oneField,
      one_collection_field: null,
      one_allowed_collections: null,
      junction_field: null,
      sort_field: null,
      one_deselect_action: 'nullify',
    },
  };
}

